// Generates the AppPaths union from the playground route config.
// Usage: node scripts/generate-app-paths.mjs
// No new dependencies: uses the TypeScript compiler API already present in devDependencies.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ts = require('typescript');

const ROUTES_FILE = process.argv[2] ?? 'src/playground/routes.tsx';
const OUT_FILE = process.argv[3] ?? 'src/playground/AppPaths.gen.ts';

const isName = (name, text) =>
	(ts.isIdentifier(name) || ts.isStringLiteralLike(name)) && name.text === text;

const propText = (object, name) =>
	object.properties.find(p => ts.isPropertyAssignment(p) && isName(p.name, name));

// Mirrors parseClientRouteItem pattern building (src/clear-router/creators/createRouter.ts):
// pattern = `${parentPattern}/${path}` with collapsed slashes.
const joinPattern = (parentPattern, path) => `${parentPattern}/${path}`.replace(/\/+/g, '/');

const collectPaths = (elements, parentPattern = '') => {
	const paths = [];
	for (const element of elements) {
		if (!ts.isObjectLiteralExpression(element)) continue;
		const pathProp = propText(element, 'path');
		if (!pathProp || !ts.isStringLiteralLike(pathProp.initializer)) {
			console.warn(`[generate-app-paths] skipping non-literal path in ${ROUTES_FILE}`);
			continue;
		}
		const pattern = joinPattern(parentPattern, pathProp.initializer.text);
		// Wildcards are not navigable destinations.
		if (!pattern.includes('*')) paths.push(pattern);
		const childrenProp = propText(element, 'children');
		if (childrenProp && ts.isArrayLiteralExpression(childrenProp.initializer)) {
			paths.push(...collectPaths(childrenProp.initializer.elements, pattern));
		}
	}
	return paths;
};

const findRouterCalls = sourceFile => {
	const calls = [];
	const visit = node => {
		if (
			ts.isCallExpression(node) &&
			ts.isIdentifier(node.expression) &&
			node.expression.text === 'createRouter' &&
			node.arguments.length > 0 &&
			ts.isArrayLiteralExpression(node.arguments[0])
		) {
			calls.push(node.arguments[0]);
		}
		ts.forEachChild(node, visit);
	};
	visit(sourceFile);
	return calls;
};

const main = () => {
	let source;
	try {
		source = readFileSync(ROUTES_FILE, 'utf8');
	} catch {
		console.error(`[generate-app-paths] cannot read ${ROUTES_FILE}`);
		process.exitCode = 1;
		return;
	}
	const sourceFile = ts.createSourceFile(ROUTES_FILE, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
	const calls = findRouterCalls(sourceFile);
	if (calls.length === 0) {
		console.error(`[generate-app-paths] no createRouter([...]) call found in ${ROUTES_FILE}`);
		process.exitCode = 1;
		return;
	}
	const paths = [...new Set(calls.flatMap(call => collectPaths(call.elements)))];
	const body = paths.map(path => `\t| '${path}'`).join('\n');
	const output = `// AUTO-GENERATED by scripts/generate-app-paths.mjs - do not edit manually.\n// Source: ${ROUTES_FILE} (${paths.length} paths)\n\nexport type AppPaths =\n${body}\n\t;\n`;
	let current = null;
	try {
		current = readFileSync(OUT_FILE, 'utf8');
	} catch {
		current = null;
	}
	if (current === output) {
		console.log(`[generate-app-paths] ${OUT_FILE} unchanged`);
		return;
	}
	writeFileSync(OUT_FILE, output);
	console.log(`[generate-app-paths] ${OUT_FILE} written (${paths.length} paths)`);
};

main();
